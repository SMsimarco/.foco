async (page) => {
  await page.evaluate(()=>Object.keys(localStorage).filter(k=>k.startsWith('foco_moments_')).forEach(k=>localStorage.removeItem(k)));
  await page.reload();
  const assert=(ok,label)=>{if(!ok)throw Error(label);};
  const close=()=>page.locator('#moment-dialog [data-m-action="close"]').click();
  const open=async name=>{await page.evaluate(name=>FocoMoments.open(name),name);};
  const count=()=>page.evaluate(()=>auditWrites.length);
  const results=[];
  await page.locator('#nav-sugerencias').click();
  await page.locator('[data-m-action="rescue"]').click();
  await page.locator('[data-rescue="0"]').waitFor();
  assert(await count()===0,'Opening rescue wrote data');
  assert(await page.locator('[data-rescue="0"]').isDisabled(),'Recurring routine editable');
  await page.evaluate(()=>auditFailure={table:'events',mode:'update',skip:2});
  await page.locator('[data-m-action="apply-rescue"]').click();
  await page.getByText('No pudimos guardar todo.',{exact:false}).waitFor();
  assert(await count()===1,'Partial update count');
  assert(await page.locator('[data-rescue="3"]').isDisabled(),'Saved row not locked');
  await page.locator('[data-m-action="apply-rescue"]').click();
  await page.locator('.mom-success').waitFor();
  assert(await count()===2,'Rescue retried already saved row');
  assert(await page.evaluate(()=>auditWrites.every(w=>w.payload.start_time===null&&w.payload.end_time===null&&!w.ids.includes('routine'))),'Rescue did not keep recurrence/time rules');
  results.push('Rescue: explicit confirmation, recurrence locked, partial retry once');
  await close();
  await open('Time');
  await page.locator('[data-energy="High"]').click();
  await page.locator('[data-m-action="recommend"]').click();
  assert((await page.locator('.mom-result h3').innerText()).includes('Enviar propuesta'),'Time candidate wrong');
  await page.locator('[data-m-action="suggest-step"]').click();
  await page.getByText('Abrí el borrador y elegí los tres puntos que querés incluir.').waitFor();
  assert(await count()===2,'Step generated writes');
  await page.locator('[data-m-action="open-task"]').click();
  assert(await page.locator('#panel-title').inputValue()==='Enviar propuesta de diseño','Wrong event opened');
  await page.evaluate(()=>closeEventPanel());
  results.push('Time: real duration, generated first step, opens original activity');
  await open('Capture');
  await page.locator('#moment-brain').fill('Pagar internet\nLlamar a mamá');
  await close();await open('Capture');
  assert((await page.locator('#moment-brain').inputValue()).includes('mamá'),'Draft lost on close');
  await page.locator('[data-m-action="organize"]').click();
  await page.locator('[data-row="1"]').waitFor();
  assert(await count()===2,'Organize wrote data');
  await page.locator('[data-m-action="save-capture"]').click();
  await page.getByText('Completá un título y una fecha válida',{exact:false}).waitFor();
  assert(await count()===2,'Invalid dates saved');
  await page.locator('[data-m-action="date-today"][data-index="0"]').click();
  await page.locator('[data-m-action="date-tomorrow"][data-index="1"]').click();
  await page.evaluate(()=>auditFailure={table:'events',mode:'insert',skip:2});
  await page.locator('[data-m-action="save-capture"]').click();
  await page.getByText('No pudimos guardar todo.',{exact:false}).waitFor();
  assert(await count()===3,'Partial insert count');
  assert(await page.locator('#moment-title-0').isDisabled(),'Inserted row not locked');
  await page.locator('[data-m-action="save-capture"]').click();
  await page.locator('.mom-success').waitFor();
  assert(await count()===4,'Capture retry duplicated rows');
  assert(await page.evaluate(()=>auditData.events.filter(e=>e.title==='Pagar internet').length)===1,'Duplicated pay task');
  results.push('Capture: draft retained, review without writes, missing dates blocked, partial retry idempotent');
  await close();await open('Close');
  await page.locator('#moment-achievement').fill('Avancé en lo importante');
  await page.locator('#moment-next').fill('Preparar una idea clara');
  await page.locator('[data-m-action="save-memory"]').click();
  await page.getByText('Día cerrado.',{exact:false}).waitFor();
  assert(await page.evaluate(()=>Object.values(JSON.parse(localStorage.getItem('foco_moments_audit-user_closings')))[0].next)==='Preparar una idea clara','Closing memory not saved');
  results.push('Closing: user-scoped local persistence');
  await close();await open('Insights');
  await page.locator('.mom-evidence').first().waitFor();
  assert((await page.locator('.mom-evidence').first().innerText()).includes('10 de 10'),'Evidence counts wrong');
  await page.locator('[data-m-action="experiment"]').click();
  assert(await page.locator('#moment-start-0').inputValue()==='09:00','Experiment not tied to evidence');
  assert(await count()===4,'Experiment saved without approval');
  results.push('Insights: counts from history and reviewable experiment');
  await close();await open('Capsule');
  await page.locator('#moment-achievement').fill('Mi primer paso constante');
  await page.locator('#moment-learn').fill('Un bloque corto me ayuda a empezar.');
  await page.locator('#moment-next').fill('Reservar veinte minutos para mi proyecto.');
  await page.locator('[data-m-action="save-memory"]').click();
  await page.getByText('Cápsula guardada.',{exact:false}).waitFor();
  const downloadPromise=page.waitForEvent('download');
  await page.locator('[data-m-action="download"]').click();
  const download=await downloadPromise;
  await download.saveAs('output/playwright/moments-capsule-card.png');
  await close();
  await page.locator('#nav-equipo').click();
  await page.locator('.mom-history summary').click();
  await page.locator('[data-capsule]').click();
  assert(await page.locator('#moment-achievement').inputValue()==='Mi primer paso constante','Capsule history lost');
  await close();
  results.push('Capsule: editable snapshot, saved history, PNG download');
  assert((await page.evaluate(()=>window.momentErrors)).length===0,'JS errors: '+await page.evaluate(()=>window.momentErrors.join(' | ')));
  return {results,writes:await count(),download:download.suggestedFilename(),errors:[]};
}
